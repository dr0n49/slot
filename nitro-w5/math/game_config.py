"""Game configuration for NITRO VEIN. All numbers come from math_params.py."""

import os
import sys

from src.config.config import Config
from src.config.distributions import Distribution
from src.config.betmode import BetMode

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import math_params as P  # noqa: E402


class GameConfig(Config):
    """Game specific configuration class."""

    _instance = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance

    def __init__(self):
        super().__init__()
        self.game_id = P.GAME_ID
        self.game_name = P.GAME_NAME
        self.provider_number = P.PROVIDER_NUMBER
        self.working_name = "Nitro Vein"
        self.wincap = P.WINCAP
        self.win_type = "ways"
        self.rtp = P.RTP
        self.construct_paths()

        # Board
        self.num_reels = P.NUM_REELS
        self.num_rows = [P.NUM_ROWS] * self.num_reels
        self.include_padding = True

        # Paytable, in the SDK's {(kind, symbol): pay-per-way} form. The values in
        # math_params.PAYTABLE are final: nothing is scaled on the way in.
        self.paytable = {}
        for symbol, pays in P.PAYTABLE.items():
            for kind, pay in pays.items():
                self.paytable[(kind, symbol)] = round(pay, 4)
        self.payout_step = P.PAYOUT_STEP

        self.special_symbols = {
            "wild": [P.WILD],
            "scatter": [P.SCATTER],
            "keg": [P.KEG],
            "rock": [P.ROCK],
        }

        # Blast ladder + free spin tables
        self.ladder = {
            self.basegame_type: list(P.LADDER["basegame"]),
            self.freegame_type: list(P.LADDER["freegame"]),
        }
        # The board can hold at most 3 scatters (reels 1/3/5, spacing 8, 6-row window), so
        # the tables have a single reachable entry. Counts above it are still mapped - a
        # board that somehow showed more must not crash the game - but they cannot occur.
        max_count = self.num_reels * P.NUM_ROWS
        trig_cap, retrig_cap = max(P.FS_TRIGGER), max(P.FS_RETRIGGER)
        self.freespin_triggers = {
            self.basegame_type: {
                c: P.FS_TRIGGER[min(c, trig_cap)] for c in range(min(P.FS_TRIGGER), max_count + 1)
            },
            self.freegame_type: {
                c: P.FS_RETRIGGER[min(c, retrig_cap)] for c in range(min(P.FS_RETRIGGER), max_count + 1)
            },
        }
        self.anticipation_triggers = {
            self.basegame_type: P.ANTICIPATION_AT_SCATTERS["basegame"],
            self.freegame_type: P.ANTICIPATION_AT_SCATTERS["freegame"],
        }

        # Reels (generated by build_reels.py from math_params.REEL_WEIGHTS)
        self.reels = {}
        for name in P.REEL_WEIGHTS:
            self.reels[name] = self.read_reels_csv(os.path.join(self.reels_path, f"{name}.csv"))

        self.bet_modes = [self._base_mode(), self._bonus_mode()]

    # ------------------------------------------------------------------ #
    def get_win_level(self, win_amount: float, winlevel_key: str) -> int:
        """Win level integer sent in the book; the frontend maps it to a presentation tier."""
        level = 1
        for lvl, threshold in sorted(P.WIN_LEVELS.items()):
            if win_amount >= threshold:
                level = lvl
        return level

    # ------------------------------------------------------------------ #
    def _reel_weights(self):
        return {
            self.basegame_type: {"BR0": 1},
            self.freegame_type: {"FR0": 1},
        }

    def _base_mode(self) -> BetMode:
        q = P.BASE_MODE["quota"]
        triggers = P.BASE_MODE["scatter_triggers"]
        used = sum(v for v in q.values() if v is not None)
        return BetMode(
            name="base",
            cost=1.0,
            rtp=self.rtp,
            max_win=P.WINCAP,
            auto_close_disabled=False,
            is_feature=True,
            is_buybonus=False,
            distributions=[
                Distribution(
                    criteria="freegame",
                    quota=q["freegame"],
                    conditions={
                        "reel_weights": self._reel_weights(),
                        "force_wincap": False,
                        "force_freegame": True,
                        "scatter_triggers": triggers,
                    },
                ),
                Distribution(
                    criteria="0",
                    quota=q["0"],
                    win_criteria=0.0,
                    conditions={
                        "reel_weights": {self.basegame_type: {"BR0": 1}},
                        "force_wincap": False,
                        "force_freegame": False,
                    },
                ),
                Distribution(
                    criteria="basegame",
                    quota=round(1.0 - used, 6),
                    conditions={
                        "reel_weights": {self.basegame_type: {"BR0": 1}},
                        "force_wincap": False,
                        "force_freegame": False,
                    },
                ),
            ],
        )

    def _bonus_mode(self) -> BetMode:
        q = P.BONUS_MODE["quota"]
        triggers = P.BONUS_MODE["scatter_triggers"]
        return BetMode(
            name="bonus",
            cost=P.BONUS_COST,
            rtp=self.rtp,
            max_win=P.WINCAP,
            auto_close_disabled=False,
            is_feature=False,
            is_buybonus=True,
            distributions=[
                Distribution(
                    criteria="freegame",
                    quota=1.0,
                    conditions={
                        "reel_weights": self._reel_weights(),
                        "force_wincap": False,
                        "force_freegame": True,
                        "scatter_triggers": triggers,
                    },
                ),
            ],
        )
