"""Export the math parameters the frontend DISPLAYS (paytable, ladder, free-spin tables, win levels).

    python games/nitro_vein/export_frontend.py [path/to/mathConfig.generated.ts]

The frontend never uses these numbers to decide an outcome, only to render the paytable / rules
and to size UI (e.g. the ladder rungs). Outcomes always come from the RGS book.
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import math_params as P  # noqa: E402


def build() -> dict:
    paytable = {
        sym: {str(k): round(v, 4) for k, v in pays.items()} for sym, pays in P.PAYTABLE.items()
    }
    return {
        "gameId": P.GAME_ID,
        "gameName": P.GAME_NAME,
        "rtp": P.RTP,
        "wincap": P.WINCAP,
        "bonusCost": P.BONUS_COST,
        "numReels": P.NUM_REELS,
        "numRows": P.NUM_ROWS,
        "symbols": {
            "paying": P.PAYING_SYMBOLS,
            "wild": P.WILD,
            "scatter": P.SCATTER,
            "keg": P.KEG,
            "rock": P.ROCK,
        },
        "paytable": paytable,
        "ladder": P.LADDER,
        "freeSpins": {
            "trigger": {str(k): v for k, v in P.FS_TRIGGER.items()},
            "retrigger": {str(k): v for k, v in P.FS_RETRIGGER.items()},
        },
        "winLevels": {str(k): v for k, v in P.WIN_LEVELS.items()},
    }


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else None
    payload = json.dumps(build(), indent="\t")
    body = (
        "// GENERATED by math-sdk/games/nitro_vein/export_frontend.py — do not edit by hand.\n"
        "// Display-only: outcomes always come from the RGS book.\n"
        f"export default {payload} as const;\n"
    )
    if out:
        with open(out, "w") as f:
            f.write(body)
        print("wrote", out)
    else:
        print(body)
